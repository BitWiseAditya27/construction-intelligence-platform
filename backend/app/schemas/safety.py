from typing import List, Optional
from pydantic import BaseModel, Field

class HazardItem(BaseModel):
    hazard: str = Field(..., description="Description of the potential hazard")
    severity: str = Field(..., description="Severity level: Low, Medium, High, or Critical")
    location: str = Field(..., description="Approximate location or context in the scene")
    recommendation: str = Field(..., description="Actionable safety precaution or fix")

class SafetyAnalyzeResponse(BaseModel):
    overall_risk: str = Field(..., description="Low, Medium, High, or Critical")
    severity: str = Field(..., description="Overall severity summary")
    observations: List[str] = Field(default_factory=list, description="Visual site conditions observed")
    hazards: List[HazardItem] = Field(default_factory=list, description="Specific identified hazards")
    recommended_actions: List[str] = Field(default_factory=list, description="Corrective actions")
    summary: str = Field(..., description="Executive summary of the safety analysis")
    limitations: str = Field(..., description="Known limitations of image-based analysis")
    disclaimer: str = Field(..., description="Legal and professional disclaimer")
    is_demo_mode: bool = Field(False, description="True if generated by local deterministic fallback")
    inspection_id: Optional[int] = None
    image_url: Optional[str] = None
    project_name: Optional[str] = None
    location: Optional[str] = None
    created_at: Optional[str] = None
