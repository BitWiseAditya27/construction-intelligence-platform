from typing import List, Optional
from pydantic import BaseModel, Field

class CrackAnalyzeResponse(BaseModel):
    observations: List[str] = Field(default_factory=list, description="Visible surface conditions and crack traits")
    location_in_image: str = Field(..., description="Approximate region of crack in image")
    crack_pattern: str = Field(..., description="Observed pattern (e.g. diagonal shear, vertical settlement, map cracking)")
    possible_causes: List[str] = Field(default_factory=list, description="Plausible engineering hypotheses (not definitive)")
    suggested_next_steps: List[str] = Field(default_factory=list, description="Recommended remediation or monitoring actions")
    professional_inspection_warranted: bool = Field(True, description="Whether an on-site structural engineer is advised")
    urgency: str = Field(..., description="Immediate, Prompt, or Monitor")
    limitations: str = Field(..., description="Limitations of photographic assessment")
    disclaimer: str = Field(..., description="Safety and engineering disclaimer")
    is_demo_mode: bool = Field(False, description="True if generated by local deterministic fallback")
    analysis_id: Optional[int] = None
    image_url: Optional[str] = None
    structure_type: Optional[str] = None
    created_at: Optional[str] = None
